#!/usr/bin/env python3
"""Synthesize the demo/test sounds from scratch (no recordings, no third-party audio).

Every file is generated by this script, so the sounds can be shared under CC0.
Usage: python3 synth_sounds.py <out_dir>
"""
import os
import sys
import wave

import numpy as np

SR = 48000
rng = np.random.default_rng(7)


def t(sec):
    return np.arange(int(SR * sec)) / SR


def env_ad(n, attack=0.005, decay=0.2):
    a = int(SR * attack)
    e = np.ones(n)
    e[:a] = np.linspace(0, 1, a)
    e[a:] = np.exp(-np.arange(n - a) / (SR * decay))
    return e


def silence(sec):
    return np.zeros(int(SR * sec))


def norm(x, peak=0.8):
    m = np.max(np.abs(x)) or 1.0
    return x / m * peak


def smoke_alarm():
    # NFPA "Temporal-3" pattern: three 0.5 s beeps, 1.5 s pause, repeated. Piezo tone near 3.1 kHz (square-ish).
    beep = np.sign(np.sin(2 * np.pi * 3100 * t(0.5))) * 0.6 + np.sin(2 * np.pi * 3100 * t(0.5)) * 0.4
    beep *= np.minimum(1, np.minimum(np.arange(len(beep)), np.arange(len(beep))[::-1]) / 200)
    cycle = np.concatenate([beep, silence(0.5), beep, silence(0.5), beep, silence(1.5)])
    return np.concatenate([cycle, cycle])


def bell(freq, sec=1.6):
    x = t(sec)
    partials = [(1, 1.0), (2.0, 0.5), (3.01, 0.25), (4.2, 0.12)]
    s = sum(a * np.sin(2 * np.pi * freq * k * x) * np.exp(-x * (1.5 + k)) for k, a in partials)
    return s * env_ad(len(x), 0.002, 10)


def doorbell():
    return np.concatenate([bell(659.25), bell(523.25, 2.0), silence(0.6), bell(659.25), bell(523.25, 2.0)])


def knock_once():
    n = int(SR * 0.12)
    noise = rng.normal(0, 1, n)
    # crude low-pass by moving average for a wooden thud
    k = 24
    noise = np.convolve(noise, np.ones(k) / k, mode='same')
    thud = np.sin(2 * np.pi * 140 * t(0.12)) * 0.8
    return (noise * 3 + thud) * env_ad(n, 0.001, 0.025)


def knock():
    seq = []
    for gap in (0.28, 0.28, 0.9, 0.28, 0.28):
        seq += [knock_once(), silence(gap)]
    return np.concatenate(seq + [knock_once(), silence(0.4)])


def microwave():
    b = np.sin(2 * np.pi * 1000 * t(0.35)) * np.minimum(1, np.minimum(np.arange(int(SR * 0.35)), np.arange(int(SR * 0.35))[::-1]) / 300)
    return np.concatenate([b, silence(0.25), b, silence(0.25), b, silence(0.8)])


def kettle():
    x = t(4.0)
    f = 1900 + 250 * np.minimum(1, x / 2.5) + 25 * np.sin(2 * np.pi * 5.5 * x)
    ph = 2 * np.pi * np.cumsum(f) / SR
    breath = rng.normal(0, 0.25, len(x))
    s = np.sin(ph) + 0.3 * np.sin(2 * ph) + breath * 0.3
    return s * np.minimum(1, x / 1.2) * np.minimum(1, (x[-1] - x) / 0.2 + 0.001)


def siren():
    x = t(4.0)
    f = 900 + 450 * np.sin(2 * np.pi * 0.5 * x)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) + 0.35 * np.sin(3 * ph)


def clap_once():
    n = int(SR * 0.09)
    s = rng.normal(0, 1, n)
    s = s - np.convolve(s, np.ones(6) / 6, mode='same')  # brighten
    return s * env_ad(n, 0.0005, 0.012)


def clapping():
    seq = []
    for _ in range(6):
        seq += [clap_once(), silence(0.32 + rng.uniform(-0.03, 0.03))]
    return np.concatenate(seq)


def washer_tune():
    # A made-up 5-note "cycle finished" jingle, used as the custom sound the demo teaches.
    notes = [(784, 0.22), (988, 0.22), (1175, 0.22), (988, 0.22), (1568, 0.5)]
    out = []
    for f, d in notes:
        x = t(d)
        s = np.sign(np.sin(2 * np.pi * f * x)) * 0.5 + np.sin(2 * np.pi * f * x) * 0.5
        out += [s * env_ad(len(x), 0.004, 0.4), silence(0.05)]
    return np.concatenate(out + [silence(0.6)])


def chord_music():
    # Plain triads, a non-alert sound used to check false alarms.
    out = []
    for root in (261.63, 349.23, 392.0, 261.63):
        x = t(0.9)
        s = sum(np.sin(2 * np.pi * root * r * x) for r in (1, 1.26, 1.5)) * np.exp(-x * 1.2)
        out.append(s)
    return np.concatenate(out)


def write(path, x):
    x = norm(x)
    pcm = (np.clip(x, -1, 1) * 32767).astype(np.int16)
    with wave.open(path, 'wb') as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


SOUNDS = {
    'smoke_alarm': smoke_alarm, 'doorbell': doorbell, 'knock': knock, 'microwave': microwave,
    'kettle': kettle, 'siren': siren, 'clapping': clapping, 'washer_tune': washer_tune, 'music': chord_music,
}

if __name__ == '__main__':
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for name, fn in SOUNDS.items():
        x = fn()
        write(os.path.join(out, f'{name}.wav'), x)
        print(name, round(len(x) / SR, 2), 's')
